const { z } = require('zod');

const ServiceProvider = require('../../../models/serviceProvider.model');
const ServiceOffering = require('../../../models/serviceOffering.model');
const ServiceBooking = require('../../../models/serviceBooking.model');
const { providersForShopper } = require('./area');
const { getAvailability } = require('../../serviceAvailability.service');
const { listServiceCategories } = require('../../serviceProvider.service');
const { SLOT_HOLDING_STATUSES } = require('../../../config/serviceBookingStatuses');
const { availableSlots, filterSlots } = require('../../../utils/serviceSlots');

const MAX_PROVIDERS = 5;
const MAX_CATEGORIES = 60;
const MAX_OFFERINGS = 4;
const MAX_SLOTS = 4;
const SLOT_DAYS = 10;
const MINUTE_MS = 60 * 1000;

const objectIdSchema = z.string().regex(/^[0-9a-f]{24}$/i);

// Provider and offering prices are stored in paisa; the model and the prompt
// only ever see rupees, so it cannot read 350000 as Rs 350,000.
const toRupees = (paisa) => Math.round(Number(paisa) || 0) / 100;

/**
 * Phase 2c service tools (docs/27 §3.4). They only read public provider data
 * and the provider's published availability; nothing here creates or changes a
 * booking. Times are generated by the server, so the model can only quote a
 * slot that really exists and is still free.
 */

function providerCard(provider) {
  return {
    providerId: String(provider._id),
    displayName: provider.displayName,
    slug: provider.slug,
    categoryName: provider.category ? provider.category.name : null,
    blockName: provider.block ? provider.block.name : null,
    distanceKm: provider.distanceKm ?? null,
    startingAtPrice: provider.startingAtPrice,
    ratingAvg: provider.ratingAvg,
    ratingCount: provider.ratingCount,
    isNew: Boolean(provider.isNew),
    topOfferings: (provider.topOfferings || []).map((offering) => ({
      offeringId: String(offering._id),
      title: offering.title,
      durationMinutes: offering.durationMinutes,
      startingAtPrice: offering.startingAtPrice,
    })),
  };
}

const findProvidersTool = {
  name: 'find_service_providers',
  argsHint: '{ query?: string, categoryId?: string, limit?: 1-5 }',
  description:
    "Find approved service providers near the shopper — in their block when a location is known, otherwise in their city, best rated first. Use short trade words (for example \"AC repair\", \"plumber\", \"deep cleaning\"). Returns each provider's id, area, start price, rating and a few services.",
  argsSchema: z
    .object({
      query: z.string().trim().max(80).optional(),
      categoryId: objectIdSchema.optional(),
      limit: z.number().int().min(1).max(MAX_PROVIDERS).optional(),
    })
    .strict(),
  async run(ctx, args) {
    const result = await providersForShopper(ctx, { q: args.query, categoryId: args.categoryId });

    const limit = args.limit || MAX_PROVIDERS;
    const items = result.items
      .filter((item) => item.acceptingNewOrders)
      .slice(0, limit)
      .map((item) => {
        const card = providerCard(item);
        ctx.rememberProvider(card);
        return {
          providerId: card.providerId,
          displayName: card.displayName,
          categoryName: card.categoryName,
          blockName: card.blockName,
          distanceKm: card.distanceKm,
          startingAtPricePkr: toRupees(card.startingAtPrice),
          ratingAvg: card.ratingAvg,
          ratingCount: card.ratingCount,
          isNew: card.isNew,
          offerings: card.topOfferings.map((offering) => ({
            offeringId: offering.offeringId,
            title: offering.title,
            durationMinutes: offering.durationMinutes,
            startingAtPricePkr: toRupees(offering.startingAtPrice),
          })),
        };
      });

    return {
      count: items.length,
      searched: result.searched,
      ...(result.note ? { note: result.note } : {}),
      items,
    };
  },
};

const listCategoriesTool = {
  name: 'list_service_categories',
  argsHint: '{}',
  description:
    'List the active service categories (for example AC repair, plumbing, cleaning). Use it to turn the shopper’s words into a category before searching.',
  argsSchema: z.object({}).strict(),
  async run() {
    const rows = await listServiceCategories();
    const items = rows.slice(0, MAX_CATEGORIES).map((category) => ({
      _id: String(category._id),
      name: category.name,
      slug: category.slug,
      parentId: category.parentId ? String(category.parentId) : null,
    }));
    return { count: items.length, items };
  },
};

function slotsOverlapBooked(start, durationMinutes, bookings) {
  const startMs = new Date(start).getTime();
  const endMs = startMs + durationMinutes * MINUTE_MS;
  return bookings.some(
    (booking) =>
      new Date(booking.scheduledStart).getTime() < endMs && new Date(booking.scheduledEnd).getTime() > startMs
  );
}

const providerSlotsTool = {
  name: 'get_provider_slots',
  argsHint: '{ providerId: string, day?: 0-9, part?: "morning" | "afternoon" | "evening" }',
  description:
    'The provider’s next free appointment times, generated from their published hours. Call it before naming any time. day 0 is today and 1 is tomorrow (Karachi time). Only quote slots returned here; the customer books on the provider’s page.',
  argsSchema: z
    .object({
      providerId: objectIdSchema,
      day: z.number().int().min(0).max(9).optional(),
      part: z.enum(['morning', 'afternoon', 'evening']).optional(),
    })
    .strict(),
  async run(ctx, args) {
    // The public rules match the provider page: only a verified, active
    // provider that is not frozen or restricted may be suggested.
    const provider = await ServiceProvider.findOne({
      _id: args.providerId,
      status: 'ACTIVE',
      verification: 'VERIFIED',
      billingStatus: { $nin: ['FROZEN', 'RESTRICTED'] },
      ...(ctx.cityId && { cityId: ctx.cityId }),
    }).lean();
    if (!provider) return { found: false, provider: null, offerings: [] };

    const [offerings, availability] = await Promise.all([
      ServiceOffering.find({ providerId: provider._id, isActive: true })
        .sort({ createdAt: -1 })
        .limit(MAX_OFFERINGS)
        .lean(),
      getAvailability(provider._id),
    ]);

    const now = Date.now();
    const horizonEnd = new Date(now + SLOT_DAYS * 24 * 60 * MINUTE_MS);
    const bookings =
      offerings.length === 0
        ? []
        : await ServiceBooking.find({
            providerId: provider._id,
            status: { $in: SLOT_HOLDING_STATUSES },
            scheduledStart: { $lt: horizonEnd },
            scheduledEnd: { $gt: new Date(now) },
          })
            .select('scheduledStart scheduledEnd')
            .lean();

    const groups = offerings.map((offering) => {
      const generated = availableSlots(availability, offering.durationMinutes, {
        days: SLOT_DAYS,
        nowMs: now,
      });
      const open = filterSlots(generated, { day: args.day ?? null, part: args.part ?? null, nowMs: now })
        .filter((slot) => !slotsOverlapBooked(slot.start, offering.durationMinutes, bookings))
        .slice(0, MAX_SLOTS)
        .map((slot) => ({ start: slot.start, label: slot.label, dateKey: slot.dateKey }));

      return {
        offeringId: String(offering._id),
        title: offering.title,
        durationMinutes: offering.durationMinutes,
        startingAtPrice: offering.startingAtPrice,
        slots: open,
      };
    });

    if (!ctx.providers.has(String(provider._id))) {
      // A search normally supplies the richer card; this keeps a direct slots
      // call valid without inventing anything.
      ctx.rememberProvider({
        ...providerCard(provider),
        categoryName: null,
        blockName: null,
        distanceKm: null,
        topOfferings: [],
      });
    }
    ctx.rememberSlots(String(provider._id), groups);

    return {
      found: true,
      provider: {
        providerId: String(provider._id),
        displayName: provider.displayName,
        slug: provider.slug,
      },
      isPublished: availability.isPublished,
      offerings: groups.map((offering) => ({
        offeringId: offering.offeringId,
        title: offering.title,
        durationMinutes: offering.durationMinutes,
        startingAtPricePkr: toRupees(offering.startingAtPrice),
        slots: offering.slots,
      })),
    };
  },
};

module.exports = { findProvidersTool, listCategoriesTool, providerSlotsTool };
